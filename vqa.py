def build_graph(node_feats, k=5):
    feats = node_feats.cpu().numpy()

    nbrs = NearestNeighbors(n_neighbors=k+1).fit(feats)
    _, idxs = nbrs.kneighbors(feats)

    edges = []
    for i in range(len(feats)):
        for j in idxs[i]:
            if i != j:
                edges.append([i, j])
                edges.append([j, i])

    return torch.tensor(edges).t().contiguous()

class QGNN(nn.Module):
    def __init__(self):
        super().__init__()

        self.node_proj = nn.Linear(768, 300)
        self.q_proj = nn.Linear(300, 300)

        self.gcn1 = GCNConv(600, 256)
        self.gcn2 = GCNConv(256, 256)

    def forward(self, x, edge_index, q_embed):
        x = self.node_proj(x)

        q = self.q_proj(q_embed)
        q_expand = q.unsqueeze(0).expand(x.size(0), -1)

        x = torch.cat([x, q_expand], dim=1)

        x = F.relu(self.gcn1(x, edge_index))
        x = self.gcn2(x, edge_index)

        return x

class ClosedModel(nn.Module):
    def __init__(self, qgnn):
        super().__init__()
        self.qgnn = qgnn
        self.fc = nn.Linear(256, 2)

    def forward(self, data):
        node_emb = self.qgnn(data.x, data.edge_index, data.q_embed)

        batch = torch.zeros(node_emb.size(0), dtype=torch.long).to(device)
        graph_emb = global_mean_pool(node_emb, batch)

        return self.fc(graph_emb)

def extract_keywords(node_emb, top_k=3):
    importance = node_emb.mean(dim=1)
    top_idx = torch.topk(importance, top_k).indices

    return [f"region_{i.item()}" for i in top_idx]

