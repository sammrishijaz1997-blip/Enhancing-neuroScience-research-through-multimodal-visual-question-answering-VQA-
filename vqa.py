def get_type(ans):
    ans = ans.lower()
    if ans in ["yes", "no"]:
        return "closed"
    elif len(ans.split()) <= 2:
        return "closed"
    else:
        return "open"

def process_vqarad():
    data = json.load(open("data/vqa-rad/train.json"))
    image_dir = "data/vqa-rad/images"

    processed = []

