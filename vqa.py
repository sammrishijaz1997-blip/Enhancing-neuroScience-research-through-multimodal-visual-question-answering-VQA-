# Map node positions to pseudo-anatomical regions
def map_to_region(idx):
    regions = [
        "upper region", "lower region", "central region",
        "left side", "right side",
        "anterior area", "posterior area"
    ]
    return regions[idx % len(regions)]


def extract_keywords(node_emb, top_k=3):
    scores = node_emb.norm(dim=1)
    top_idx = torch.topk(scores, top_k).indices

    keywords = [map_to_region(i.item()) for i in top_idx]
    return keywords

def generate_answer(keywords, question):
    q = question.lower()

    if "what" in q:
        return f"The image indicates abnormality in the {keywords[0]}."

    elif "where" in q:
        return f"The finding is located in the {keywords[0]}."

    elif "how many" in q:
        return f"Multiple regions are involved, including the {keywords[0]} and {keywords[1]}."

    else:
        return f"Relevant areas include the {', '.join(keywords)}."

